// subst applies all 8 nibble substitutions to a 32-bit word.
func (s *Sbox) subst(x uint32) uint32 {
	return uint32(s[0][(x>>0)&0xf])<<0 |
		uint32(s[1][(x>>4)&0xf])<<4 |
		uint32(s[2][(x>>8)&0xf])<<8 |
		uint32(s[3][(x>>12)&0xf])<<12 |
		uint32(s[4][(x>>16)&0xf])<<16 |
		uint32(s[5][(x>>20)&0xf])<<20 |
		uint32(s[6][(x>>24)&0xf])<<24 |
		uint32(s[7][(x>>28)&0xf])<<28
}

// pass applies S-box substitution then left-rotates by 11 bits.
func (s *Sbox) pass(x uint32) uint32 {
	x = s.subst(x)
	return x<<11 | x>>(32-11)
}

// Pass is the exported form of pass for use by other packages (e.g. gost34311).
func (s *Sbox) Pass(x uint32) uint32 { return s.pass(x) }

