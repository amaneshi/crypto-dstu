package gost28147

// Sbox represents 8 substitution rows of 16 nibble entries each.
// Sbox[i][j] gives the 4-bit output for nibble j in row i.
// Row 0 substitutes bits 3:0, row 1 bits 7:4, ..., row 7 bits 31:28.
// This layout matches PrivatBank cryptonite GOST28147_SBOX_* and gogost Sbox.
type Sbox [8][16]byte

// Packed returns the 64-byte DKE encoding used by Ukrainian algorithm parameters.
func (s *Sbox) Packed() []byte {
	dke := make([]byte, 64)
	for row := range 8 {
		for col := 0; col < 16; col += 2 {
			dke[row*8+col/2] = s[row][col]<<4 | s[row][col+1]
		}
	}
	return dke
}

