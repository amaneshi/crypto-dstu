// See docs/licenses/cryptonite.txt and docs/onb.md for provenance and limits.
func newONBCurve(m int, mod gf2m.ModBits, a int, b, n, x, y, root string) *Curve {
	words := mod.WordCount()
	basis := newNormalBasis(mod, mustFromHex(root, words))
	decode := func(s string) gf2m.Element { return applyBasis(basis.toPolynomial, mustFromHex(s, words), words) }
	cofactor := 2
	if a == 0 {
		cofactor = 4
	}
	nBytes := mustFromHex(n, words).Bytes()
	curve := NewCurve(m, mod, gf2m.FromBytes([]byte{byte(a)}, words), decode(b), decode(x), decode(y), nBytes, cofactor)
	curve.basis = basis
	return curve
}

